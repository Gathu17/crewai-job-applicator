class ResumeCrewRequest(BaseModel):
    """Request for ResumeCrew workflow execution."""
    job_input: str
    base_resume: str
    company_name: Optional[str] = None

    @field_validator("base_resume", mode="before")
    @classmethod
    def _normalize_base_resume(cls, v: str) -> str:
        """Allow base_resume to be sent as base64-encoded PDF and auto-extract text."""
        if isinstance(v, str):
            return extract_text_from_pdf_if_base64(v)
        return v


class ResumeCrewResponse(BaseModel):
    """Response from ResumeCrew workflow execution."""
    job_analysis: Dict[str, Any]
    company_research: Dict[str, Any]
    tailor_recommendations: Dict[str, Any]
    generated_resume: Dict[str, Any]
    workflow_report: Dict[str, Any]


@router.post("/resume-crew", response_model=ResumeCrewResponse)
async def run_resume_crew(request: ResumeCrewRequest):
    """
    Run the ResumeCrew workflow with YAML-configured agents.

    This endpoint uses the ResumeCrew class which loads all agent and task
    configurations from YAML files, providing a centralized and maintainable
    way to manage prompts.

    The workflow uses the @crew decorator pattern from CrewAI, which automatically
    orchestrates all agents and tasks in the proper sequence.

    Args:
        job_input: Job URL or job posting text
        base_resume: Your base resume content
        company_name: Optional company name (extracted from job if not provided)

    Returns:
        Complete workflow results including:
        - Job analysis
        - Company research
        - Resume tailoring recommendations
        - Generated optimized resume
        - Comprehensive workflow report
    """
    try:
        # Create ResumeCrew instance with input data
        resume_crew_instance = ResumeCrew(
            job_input=request.job_input,
            base_resume=request.base_resume,
            company_name=request.company_name
        )
        
        result = resume_crew_instance.crew().kickoff()

        # Parse the result
        import json
        import re

        try:
            parsed_result = json.loads(str(result))
        except json.JSONDecodeError:
            
            json_match = re.search(r'\{.*\}', str(result), re.DOTALL)
            if json_match:
                parsed_result = json.loads(json_match.group())
            else:
                
                parsed_result = {
                    "job_analysis": {},
                    "company_research": {},
                    "tailor_recommendations": {},
                    "generated_resume": {"content": str(result)},
                    "workflow_report": {"summary": str(result)}
                }

        # Ensure all required fields are present
        response_data = {
            "job_analysis": parsed_result.get("job_analysis", {}),
            "company_research": parsed_result.get("company_research", {}),
            "tailor_recommendations": parsed_result.get("tailor_recommendations", {}),
            "generated_resume": parsed_result.get("generated_resume", {}),
            "workflow_report": parsed_result.get("workflow_report", {})
        }

        return ResumeCrewResponse(**response_data)
    except Exception as e:
        import traceback
        error_detail = f"ResumeCrew workflow failed: {str(e)}\n{traceback.format_exc()}"
        raise HTTPException(status_code=500, detail=error_detail)

