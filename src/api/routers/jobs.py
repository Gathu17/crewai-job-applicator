"""
Jobs API router - Handles all job-related endpoints.
"""
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, field_validator
from typing import Optional, Dict, Any

from src.services.crew_runner import CrewRunner, ResumeCrew
from src.core.models.schemas import (
    JobSearchRequest,
    JobSearchResponse,
    MatchRequest,
    MatchResponse,
    TailorRequest,
    TailorResponse,
    ApplyRequest,
    ApplyResponse,
    JobAnalysis,
    CompanyResearch,
    TailorResult,
    GeneratedResume,
    WorkflowReport
)
from src.core.utils.pdf import extract_text_from_pdf_bytes

router = APIRouter(prefix="/jobs", tags=["Jobs"])

# Initialize crew runner (shared instance)
crew_runner = CrewRunner()


@router.post("/search", response_model=JobSearchResponse)
async def search_jobs(request: JobSearchRequest):
    """
    Search for job opportunities using the job scout agent.
    
    This endpoint uses the CrewAI job scout agent to discover job opportunities
    based on the provided search criteria.
    """
    try:
        jobs = crew_runner.run_job_scout(
            search_criteria=request.criteria,
            config=request.config
        )
        return JobSearchResponse(
            jobs=jobs,
            total=len(jobs),
            message=f"Found {len(jobs)} job opportunities"
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Job search failed: {str(e)}")


@router.post("/match", response_model=MatchResponse)
async def match_jobs(request: MatchRequest):
    """
    This endpoint uses the matcher agent to analyze job descriptions and
    match them with the provided resume context using RAG techniques.
    """
    try:
        matches = crew_runner.run_matcher(
            job_postings=request.job_postings,
            resume_context=request.resume_context,
            config=request.config
        )
        
        return MatchResponse(
            matches=matches,
            total_matched=len(matches),
            message=f"Matched {len(matches)} jobs"
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Job matching failed: {str(e)}")


@router.post("/tailor", response_model=TailorResponse)
async def tailor_documents(request: TailorRequest):
    """
    Generate tailored resume and cover letter for a specific job.
    
    This endpoint uses the tailor agent to create customized documents
    optimized for the specified job posting.
    """
    try:
        tailored_docs = crew_runner.run_tailor(
            job_posting=request.job_posting,
            base_resume=request.base_resume,
            config=request.config
        )
        
        job_id = request.job_posting.id or "unknown"
        
        return TailorResponse(
            job_id=job_id,
            resume=tailored_docs.get("resume", ""),
            cover_letter=tailored_docs.get("cover_letter", ""),
            format="markdown",
            message="Documents tailored successfully"
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Document tailoring failed: {str(e)}")


@router.post("/apply", response_model=ApplyResponse)
async def apply_to_job(request: ApplyRequest):
    """
    Submit a job application using the applicator agent.
    
    This endpoint uses the applicator agent to submit job applications.
    By default, applications require manual review unless auto-submit is enabled.
    """
    try:
        result = crew_runner.run_applicator(
            job_posting=request.job_posting,
            tailored_resume=request.tailored_resume,
            cover_letter=request.cover_letter,
            config=request.config
        )
        
        job_id = request.job_posting.id or "unknown"
        
        return ApplyResponse(
            application_id=None,  # Would be generated by storage layer
            status=result.get("status", "pending"),
            message=result.get("message", "Application processed"),
            job_id=job_id,
            submitted_at=None  # Would be set if actually submitted
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Application submission failed: {str(e)}")


